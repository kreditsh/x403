// The registry lives once, at the repo root. The package carries a generated copy so a
// published build has no path outside itself, and a test checks the two never drift.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const source = resolve(here, "../../../registry/reason-codes.json");
const target = resolve(here, "../src/reason-codes.ts");
const json = JSON.parse(readFileSync(source, "utf8"));
mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  "// Generated by scripts/sync-registry.mjs from registry/reason-codes.json. Do not edit.\n" +
    "export const REGISTRY = " +
    JSON.stringify(json, null, 2) +
    " as const;\n",
);
console.log("registry synced:", Object.keys(json.codes).length, "codes");
